#include <stdio.h>

#define NMAX 10

// Считывает 10 целых чисел в массив; возвращает 1 при успехе и 0 при ошибке.
int input(int *a, int n);
// Сортирует массив по возрастанию простым обменным методом.
void sort(int *a, int n);
// Выводит массив в одну строку через пробел.
void output(int *a, int n);

// Точка входа программы Quest 5.
int main(void) {
    // Создаем массив фиксированной длины 10 по условию задачи.
    int data[NMAX];

    // Если ввод корректный, сортируем и печатаем результат.
    if (input(data, NMAX) == 1) {
        sort(data, NMAX);
        output(data, NMAX);
    } else {
        // При любой ошибке ввода выводим n/a.
        printf("n/a");
    }

    return 0;
}

int input(int *a, int n) {
    // Флаг успешности ввода.
    int ok = 1;

    // Читаем ровно n чисел, как требует задание.
    for (int i = 0; i < n && ok == 1; i++) {
        if (scanf("%d", &a[i]) != 1) {
            ok = 0;
        }
    }

    return ok;
}

void sort(int *a, int n) {
    // Внешний цикл задает позицию, которую заполняем минимальным из оставшихся.
    for (int i = 0; i < n - 1; i++) {
        // Внутренний цикл перебирает элементы правее текущей позиции.
        for (int j = i + 1; j < n; j++) {
            // Если нашли элемент меньше текущего, меняем их местами.
            if (a[j] < a[i]) {
                int temp = a[i];
                a[i] = a[j];
                a[j] = temp;
            }
        }
    }
}

void output(int *a, int n) {
    // Печатаем все элементы через пробел без пробела в конце строки.
    for (int i = 0; i < n; i++) {
        if (i > 0) {
            printf(" ");
        }
        printf("%d", a[i]);
    }
}
