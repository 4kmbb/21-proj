#include "data_io.h"

#include <stdio.h>

/*
 * Читаем n чисел из стандартного потока ввода (stdin).
 * Массив data уже должен быть выделен вызывающей стороной,
 * потому что эта функция не знает, откуда взялось n.
 */
void input(double* data, int n) {
    for (int i = 0; i < n; i++) {
        // %lf нужен именно для double, а не для float
        scanf("%lf", &data[i]);
    }
}

/*
 * Печатаем массив в одну строку.
 * Числа разделяем пробелом, но после последнего числа пробел не ставим,
 * чтобы в конце строки не было "лишнего" символа.
 */
void output(double* data, int n) {
    for (int i = 0; i < n; i++) {
        if (i > 0) {
            printf(" ");
        }
        // По условию задачи все double выводим с двумя знаками после запятой
        printf("%.2f", data[i]);
    }
}
